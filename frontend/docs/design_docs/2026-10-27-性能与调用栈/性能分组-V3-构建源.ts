// 只构建静态设计。画面来自两份历史原件，重复用于布局；时间与指标为模拟数据。
export function 构建画面联动稿(旧稿) {
  const 主 = structuredClone(旧稿.boards[0]);
  主.name = '性能 · V3 画面与采样点联动';
  主.x = 0;
  主.children = 主.children.filter(层 => !['画面关闭 / 紧凑行', '独立面板布局 / 无共用外框', '调用栈 / 独立紧凑章节', '设计示例标识'].includes(层.name));
  const 色 = { 文: '#23272E', 次: '#657186', 线: '#E6EAF3', 紫: '#6C4CF5', 蓝: '#2F7FE0', 绿: '#168577', 选: '#F4F0FF' };
  const 层 = (父, type, name, x, y, w, h, fill = null, stroke = null, radius = 0) => {
    const 值 = { type, name, x, y, w, h, fill, stroke, radius, children: [] };
    if (父) 父.children.push(值);
    return 值;
  };
  const 文 = (父, name, text, x, y, w, h = 22, size = 12, fill = 色.次, weight = '400', mono = false, align = 'left') => Object.assign(层(父, 'text', name, x, y, w, h, fill), { text, size, weight, font: mono ? 'JetBrains Mono' : 'Noto Sans SC', align });
  const 点 = (父, name, x, y, fill, r, stroke = null) => 层(父, 'ellipse', name, x - r, y - r, r * 2, r * 2, fill, stroke);
  const 路 = (父, name, points, stroke, strokeWidth = 2, fill = null, close = false) => Object.assign(层(父, 'path', name, 0, 0, 848, 58, fill, stroke), { points, strokeWidth, close });
  const 时 = [0, 4, 8, 12, 16, 20, 24, 28, 32];
  const 所选 = 5;
  const 绘图起点 = 224;
  const 图宽 = 848;
  const x位 = i => 绘图起点 + 时[i] / 32 * 图宽;
  const 样本 = [
    { 名: '帧率', 值: '28.2', 单位: 'fps', 色: 色.紫, 顶: 60, 辅助: '平均 50.7 · 最低 28.2', 数值: [58, 60, 57, 55, 34, 28.2, 45, 59, 60] },
    { 名: 'CPU', 值: '22', 单位: '%', 色: 色.蓝, 顶: 50, 辅助: '应用 CPU · 峰值 44%', 数值: [12, 15, 18, 20, 44, 22, 30, 15, 14] },
    { 名: '内存', 值: '0.37', 单位: 'GB', 色: 色.绿, 顶: 0.5, 辅助: 'PSS · RSS 未采集', 数值: [0.28, 0.30, 0.31, 0.34, 0.38, 0.37, 0.38, 0.36, 0.35] },
  ];
  主.children.find(项 => 项.name === '会话计数').text = '32 s · 9 个采样点';
  主.children.find(项 => 项.name === '会话计数').w = 250;
  const 画面 = 层(主, 'board', '采样画面 / 与下方指标同一时间坐标', 264, 180, 1132, 168, '#FFFFFF', 色.线, 10);
  文(画面, '画面章节', '采样画面', 20, 12, 130, 24, 14, 色.文, '500');
  文(画面, '示例素材标识', '历史画面 · 布局示例', 164, 13, 336, 22, 11);
  点(画面, '采集启用标记', 904, 24, 色.绿, 3);
  文(画面, '画面采集状态', '画面采集已开启', 916, 13, 184, 22, 12, 色.次, '400', false, 'right');
  文(画面, '当前画面标题', '当前采样点', 20, 48, 150, 22, 12);
  文(画面, '当前画面编号', '#06', 20, 72, 150, 30, 25, 色.文, '500', true);
  文(画面, '当前采样时间', '20.00 s', 20, 108, 150, 24, 13, 色.紫, '500', true);
  文(画面, '画面交互提示', '点击画面定位指标', 20, 138, 170, 18, 11);
  const 选中X = x位(所选);
  层(画面, 'rectangle', '选中画面浅底', 选中X - 51, 47, 102, 111, 色.选, null, 7);
  for (let i = 0; i < 时.length; i++) {
    const x = x位(i);
    const 框 = 层(画面, 'board', `采样点 #${String(i + 1).padStart(2, '0')} / 画面中心与曲线对齐`, x - 45, 55, 90, 50.625, null, null, 4);
    const 图片 = 层(框, 'image', '历史游戏缩略图 / 静态布局样例', 0, 0, 90, 50.625, null, null, 4);
    图片.asset = `assets/画面缩略图-0${i % 2 + 1}.jpg`;
    层(框, 'rectangle', '缩略图边框', 0, 0, 90, 50.625, null, i === 所选 ? 色.紫 : '#DDE3EC', 4);
    文(画面, '画面对应采样点编号', `#${String(i + 1).padStart(2, '0')}`, x - 45, 111, 90, 20, 11, i === 所选 ? 色.紫 : 色.次, i === 所选 ? '500' : '400', true, 'center');
    文(画面, '画面对应时间', `${时[i].toFixed(0)} s`, x - 45, 136, 90, 19, 11, i === 所选 ? 色.紫 : 色.次, '400', true, 'center');
    点(画面, '时间轴采样点', x, 132, i === 所选 ? 色.紫 : '#C9CFDD', i === 所选 ? 3 : 2);
  }
  层(画面, 'rectangle', '所选点与时间轴连接线', 选中X - 0.5, 105.625, 1, 26, 色.紫);
  样本.forEach((项, 序) => {
    const 组 = 层(主, 'board', `独立指标面板 / ${项.名}`, 264, 364 + 序 * 124, 1132, 108, '#FFFFFF', 色.线, 10);
    点(组, '指标图例圆点', 23, 24, 项.色, 3);
    文(组, '指标名称', 项.名, 34, 12, 140, 24, 14, 色.文, '500');
    文(组, '当前读数', 项.值, 20, 37, 104, 32, 26, 色.文, '500', true);
    文(组, '读数单位', 项.单位, 项.名 === 'CPU' ? 71 : 108, 47, 60, 22, 12);
    文(组, '辅助口径', 项.辅助, 20, 79, 182, 19, 11);
    const 图 = 层(组, 'board', `${项.名} / 独立绘图区`, 绘图起点, 19, 图宽, 58, null);
    [0, 0.5, 1].forEach(比 => {
      层(图, 'rectangle', '少量辅助网格', 0, 比 * 54, 图宽, 1, '#F0F2F7');
      文(组, '本指标纵轴', `${项.顶 * (1 - 比)}`, 绘图起点 - 38, 9 + 比 * 54, 27, 20, 10, 色.次, '400', true, 'right');
    });
    const 点集 = 项.数值.map((值, i) => [时[i] / 32 * 图宽, (1 - 值 / 项.顶) * 54]);
    const 填色 = 路(图, `${项.名} / 极浅面积`, [[0, 54], ...点集, [图宽, 54]], null, 0, 项.色, true);
    填色.opacity = 0.045;
    层(图, 'rectangle', '选中采样点浅底', 选中X - 绘图起点 - 8, 0, 16, 58, '#F8F5FF', null, 3);
    路(图, `${项.名} / 指标趋势`, 点集, 项.色, 1.8);
    点集.forEach(([x, y], i) => { if (i !== 所选) 点(图, '采样点', x, y, 项.色, 1.8); });
    层(图, 'rectangle', '与画面同点的选中线', 选中X - 绘图起点 - 0.5, 0, 1, 58, '#AB95F7');
    点(图, '选中点白色外环', 点集[所选][0], 点集[所选][1], '#FFFFFF', 5);
    点(图, '选中数据点', 点集[所选][0], 点集[所选][1], 项.色, 3);
    时.forEach((t, i) => 文(组, '本面板时间刻度', `${t} s`, x位(i) - 22, 83, 44, 18, 10, i === 所选 ? 色.紫 : 色.次, '400', true, 'center'));
  });
  const 栈 = 层(主, 'board', '调用栈 / 独立收起章节', 264, 736, 1132, 36, '#FFFFFF', 色.线, 8);
  文(栈, '调用栈名称', '调用栈', 20, 7, 104, 22, 13, 色.文, '500');
  文(栈, '栈样本状态', '当前采样点无栈样本', 124, 7, 400, 22, 12);
  文(栈, '选中采样点引用', '#06 · 20.00 s', 800, 7, 312, 22, 12, 色.次, '400', true, 'right');
  return { version: 3, product: 'FORGE / DeviceForge', mock: { times: 时, selected: 所选, assetCount: 2, repeatedForLayout: true }, boards: [主] };
}
