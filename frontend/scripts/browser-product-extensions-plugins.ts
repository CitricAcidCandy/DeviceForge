import { button, check, click, field, fill, pause, select, until, upload } from './session-browser-actions.ts';
import type { ExtensionBrowserContext } from './browser-product-extensions-context.ts';
import { closeExtensionDialog, navigateExtensionPage } from './browser-product-extensions-context.ts';
import { extensionObject, extensionPluginId, extensionThemeId, extensionThemeValue, extensionVariable } from './browser-product-extensions-fixture.ts';

export async function verifyExtensionProductPage(context: ExtensionBrowserContext) {
  const {target, extensionRoot, fixture, services, passed} = context;
  const importCount = () => fixture.imports.length;
  const ready = (label: string) => [...target.querySelectorAll('button')].some(entry => !entry.closest('[hidden]') && entry.textContent?.trim() === label && !entry.disabled);
  await navigateExtensionPage('settings', '设置'); const draftNode = field('配置内容 · JSON'); const draft = draftNode.value;
  await navigateExtensionPage('tasks', '任务与日志'); await fill('操作名或任务 ID', '保留任务筛选'); await select('任务状态', '成功');
  const queryNode = field('操作名或任务 ID'); const query = queryNode.value;
  const filterNode = document.getElementById('task-filter'); check(filterNode instanceof HTMLButtonElement, '任务筛选Select不存在');
  const taskResult = services.runtime.tasks.snapshot().result;
  await navigateExtensionPage('plugins', '插件'); await select('部署到', '浏览器插件');
  await until(() => target.textContent?.includes('还没有部署插件包') === true && !button('刷新目录').disabled, '浏览器包目录尚未就绪');
  check(button('提交插件包').disabled, '未选包仍允许提交'); passed('浏览器包目录与上传准入');
  await upload('插件包 · ZIP / TGZ', 'fixture-browser.zip'); await click('提交插件包');
  await until(() => document.querySelector('.plugin-row h3')?.textContent?.includes(extensionPluginId) === true && !button('启用').disabled, '上传没有刷新部署目录');
  check(fixture.packageCount() === 1 && importCount() === 0, '提交包时便执行插件或没有部署记录'); passed('产品上传使用公开ZIP原字节接口且等待启用');
  await click('启用'); await until(() => fixture.lifecycle.activated === 1 && ready('停用'), '公开包启用没有完成');
  check(importCount() === 1 && fixture.imports[0]?.includes(extensionPluginId), '启用没有通过已安装包入口导入'); passed('页面启用经可信安装包加载器');
  check(button(`删除已部署的 ${extensionPluginId}`).disabled, '运行中的浏览器包允许直接删除'); passed('运行中包删除入口收敛');
  check(button('未提供槽位组件 · 挂载组件').disabled, '宿主不存在的槽位仍允许挂载'); passed('未提供槽位的组件禁用');
  await click('受控模块 · 打开模块'); await until(() => extensionRoot.textContent?.includes('受控模块内容') === true, '公开模块未挂载');
  passed('模块通过产品入口挂载');
  await click('受控模块 · 关闭模块'); await until(() => !extensionRoot.textContent?.includes('受控模块内容'), '关闭模块未释放内容');
  passed('模块撤销释放DOM');
  await click('追加组件 · 挂载组件'); await until(() => extensionRoot.textContent?.includes('追加组件内容') === true, '追加组件未挂载');
  check(extensionRoot.querySelector('[data-fixture-default-slot]'), '追加组件移除了宿主默认区'); passed('追加组件保留默认扩展区');
  await click('追加组件 · 撤销挂载'); await until(() => !extensionRoot.textContent?.includes('追加组件内容'), '追加组件未撤销'); passed('追加组件撤销释放DOM');
  await click('替换组件 · 挂载组件'); await until(() => extensionRoot.textContent?.includes('替换组件内容') === true, '替换组件未挂载');
  check(!extensionRoot.querySelector('[data-fixture-default-slot]'), '替换组件未释放默认渲染'); passed('替换组件使用公开槽位租约');
  await click('替换组件 · 撤销挂载'); await until(() => extensionRoot.querySelector('[data-fixture-default-slot]') !== null, '撤销替换没有恢复默认区');
  passed('撤销替换恢复宿主默认扩展区');
  await select('选择主题', '受控公开主题');
  await until(() => services.runtime.themes.snapshot().selected?.id === extensionThemeId, '主题公开选择未生效');
  check(document.documentElement.style.getPropertyValue(extensionVariable) === extensionThemeValue, '主题变量没有施加到文档根'); passed('公开主题施加到文档根');
  check(draftNode.isConnected && draftNode.value === draft && queryNode.isConnected && queryNode.value === query && filterNode.textContent === '成功', '主题切换改变已挂载页面草稿或筛选');
  check(services.runtime.tasks.snapshot().result === taskResult, '主题切换改变任务结果'); passed('主题切换保留草稿筛选与任务结果');
  await click('受控命令 · 执行命令'); await until(() => document.querySelector('[role="dialog"]') !== null, '命令没有官方弹窗');
  const dialog = document.querySelector('[role="dialog"]'); check(dialog instanceof HTMLElement, '命令弹窗不是真实DOM');
  check(!target.contains(dialog) && getComputedStyle(dialog).getPropertyValue(extensionVariable).trim() === extensionThemeValue, '官方Portal未继承主题变量');
  passed('官方Dialog Portal继承插件主题');
  const callsBefore = fixture.calls.length; await fill('扩展输入 · JSON', '{非法JSON'); await click('执行', dialog);
  await until(() => !button('执行', dialog).disabled, '命令非法JSON反馈未结束'); check(fixture.calls.length === callsBefore, '非法扩展JSON进入插件');
  passed('命令非法JSON零调用');
  await fill('扩展输入 · JSON', '{"enabled":false,"count":0,"text":"公开命令🙂"}'); await click('执行', dialog);
  await until(() => dialog.textContent?.includes('命令公开结果') === true, '命令公开结果未展示');
  const command = fixture.calls.at(-1); check(command?.kind === '命令' && extensionObject(command.input) && command.input['count'] === 0 && command.input['enabled'] === false && command.aborted === false, '命令输入或取消契约未保留');
  check(dialog.textContent?.includes('extension-call-log'), '命令结果没有公开日志ID'); passed('命令弹窗传递原值并展示结果与日志ID');
  await closeExtensionDialog();
  const summary = [...document.querySelectorAll('summary')].find(item => !item.closest('[hidden]') && item.textContent?.startsWith('公开扩展服务'));
  check(summary instanceof HTMLElement, '公开服务目录折叠项不存在'); summary.click(); await pause();
  await click(`${extensionPluginId}.service · 1`); const serviceDialog = document.querySelector('[role="dialog"]'); check(serviceDialog instanceof HTMLElement, '服务没有官方弹窗');
  await fill('扩展输入 · JSON', '[0,false,"公开服务"]'); await click('执行', serviceDialog);
  await until(() => serviceDialog.textContent?.includes('服务公开结果') === true, '服务结果未展示');
  const serviceCall = fixture.calls.at(-1); check(serviceCall?.kind === '服务' && Array.isArray(serviceCall.input) && serviceCall.input[0] === 0 && serviceCall.input[1] === false && !serviceCall.aborted, '服务原始数组输入未传递');
  passed('公开版本服务通过Dialog输入与结果'); await closeExtensionDialog();
  await select('选择主题', '工坊默认主题'); check(document.documentElement.style.getPropertyValue(extensionVariable) === '宿主原始值', '撤销主题未恢复原始变量');
  passed('撤销主题恢复宿主原值');
  await navigateExtensionPage('settings', '设置'); check(field('配置内容 · JSON') === draftNode && draftNode.value === draft, '主题撤销后配置页重建或草稿改变');
  await select('工作空间主题', '受控公开主题'); check(services.runtime.themes.snapshot().selected?.id === extensionThemeId, '设置页未同步公开主题');
  passed('设置页消费同一主题目录且保留草稿');
  await navigateExtensionPage('tasks', '任务与日志'); check(field('操作名或任务 ID') === queryNode && queryNode.value === query && filterNode.textContent === '成功', '主题撤销后任务筛选未保留');
  passed('跨路由保留相同任务筛选节点');
  await navigateExtensionPage('plugins', '插件'); await click('受控模块 · 打开模块'); await click('追加组件 · 挂载组件');
  await click('停用'); await until(() => fixture.lifecycle.deactivated === 1 && ready('启用'), '页面停用未完成');
  check(!extensionRoot.textContent?.includes('受控模块内容') && !extensionRoot.textContent?.includes('追加组件内容') && fixture.lifecycle.released === fixture.lifecycle.mounted, '停用未释放全部已挂载扩展');
  check(services.runtime.extensions.catalog().commands.every(entry => entry.pluginId !== extensionPluginId), '停用未撤销插件命令目录');
  passed('停用释放挂载资源并撤销扩展目录');
  check(services.runtime.themes.snapshot().selected === null && document.documentElement.style.getPropertyValue(extensionVariable) === '宿主原始值', '停用未撤销当前主题');
  passed('停用撤销所属主题并恢复宿主');
  await click('启用'); await until(() => fixture.lifecycle.activated === 2 && ready('停用'), '重新启用未完成');
  check(importCount() === 2 && fixture.imports[0] !== fixture.imports[1], '重新启用复用旧ESM运行代次'); passed('重新启用刷新包运行代次');
  check([...target.querySelectorAll('button')].some(entry => entry.textContent?.trim() === '受控模块 · 打开模块') && [...target.querySelectorAll('button')].some(entry => entry.textContent?.trim() === '追加组件 · 挂载组件'), '重新启用残留旧挂载状态，首击会错误撤销');
  await click('受控模块 · 打开模块'); await until(() => extensionRoot.textContent?.includes('受控模块内容') === true, '重新启用后首次模块挂载未生效');
  passed('停用重启清除旧挂载状态且首击生效');
  await click('停用'); await until(() => ready('启用'), '删除前停用未结束');
  await click(`删除已部署的 ${extensionPluginId}`); await until(() => fixture.packageCount() === 0 && !document.querySelector('.plugin-row'), '删除部署包未刷新目录');
  passed('停用后删除部署包并刷新目录');
}
