import { button, check, click, field, fill, pause, select, until } from './session-browser-actions.ts';
import type { ExtensionBrowserContext } from './browser-product-extensions-context.ts';
import { navigateExtensionPage } from './browser-product-extensions-context.ts';
import { extensionObject } from './browser-product-extensions-fixture.ts';

export async function verifySettingsProductPage(context: ExtensionBrowserContext) {
  const {target, fixture, passed} = context; const settings = fixture.settings;
  await navigateExtensionPage('settings', '设置');
  await until(() => !button('读取配置').disabled, '公开配置操作没有开放');
  check(button('保存此区').disabled, '未读取修订便允许配置写入'); passed('未读取修订时禁用写入');
  await click('读取配置'); await until(() => target.textContent?.includes('当前修订：1') === true, '配置修订未显示');
  passed('读取配置保留真实修订');
  await click('读取此区'); await until(() => field('配置内容 · JSON').value.includes('初始本地配置'), '读取配置区没有回填JSON草稿');
  passed('读取配置区回填专用草稿');
  await fill('配置内容 · JSON', '{"label":"首次页面写入","zero":0,"enabled":false}');
  await click('保存此区'); await until(() => settings.snapshot().revision === '2' && !button('保存此区').disabled, '配置首次保存未完成');
  const first = settings.writes.find(entry => entry.operation === 'plugin.settings.set');
  check(first?.input['expected_revision'] === '1' && extensionObject(first.input['value']) && first.input['value']['zero'] === 0 && first.input['value']['enabled'] === false, '公开CAS输入或零值未保留');
  passed('CAS保存携带已读修订与原始JSON类型');
  check(target.textContent?.includes('当前修订：2'), '保存后页面修订未更新'); passed('成功保存更新页面修订');
  const count = () => settings.writes.filter(entry => entry.operation === 'plugin.settings.set').length;
  const beforeInvalid = count(); await fill('配置内容 · JSON', '{坏JSON'); await click('保存此区');
  await until(() => !button('保存此区').disabled, '非法JSON处理未结束'); check(count() === beforeInvalid, '非法JSON进入服务器任务');
  passed('非法配置JSON在提交前拒绝');
  settings.concurrentWrite(); await fill('配置内容 · JSON', '{"label":"不得覆盖的过时草稿"}');
  const beforeConflict = count(); await click('保存此区');
  await until(() => target.textContent?.includes('配置修订冲突，请重查后修改') === true, 'CAS冲突未呈现');
  check(count() === beforeConflict + 1, '冲突发生额外提交'); passed('CAS冲突明确呈现');
  for (let tick = 0; tick < 12; tick++) await pause();
  check(count() === beforeConflict + 1 && JSON.stringify(settings.snapshot().sections['general']).includes('并发写入受保护值'), '冲突后自动重放或覆盖远端配置');
  passed('冲突零自动重放且保护并发写入');
  check(field('配置内容 · JSON').value.includes('不得覆盖的过时草稿'), '冲突丢失用户草稿'); passed('冲突保留用户草稿');
  await click('读取此区'); await until(() => field('配置内容 · JSON').value.includes('并发写入受保护值'), '冲突后重新读取未恢复最新值');
  await fill('配置内容 · JSON', '{"label":"重查后合法写入"}'); await click('保存此区');
  await until(() => settings.snapshot().revision === '4' && !button('保存此区').disabled, '重查后的保存未完成');
  check(settings.writes.at(-1)?.input['expected_revision'] === '3', '重查后未消费新修订'); passed('用户重查后使用新修订保存');
  await click('读取远端'); await until(() => target.textContent?.includes('实际来源：本地备份 · 远端已提交：否 · 本地备份已更新：否') === true, '本地回退来源未显示');
  check(field('远端内容 · JSON 原值').value.includes('本地备份值'), '本地回退内容未呈现'); passed('本地回退分别呈现来源与未提交未更新');
  settings.setRemote('remote', {label: '远端读取值', enabled: false}); await click('读取远端');
  await until(() => target.textContent?.includes('实际来源：远端服务 · 远端已提交：否 · 本地备份已更新：是') === true, '远端读取备份状态未显示');
  check(settings.snapshot().revision === '5' && field('远端内容 · JSON 原值').value.includes('远端读取值'), '远端读取没有更新本地修订与草稿');
  passed('远端读取区分备份更新与未提交');
  const backup = document.getElementById('remote-backup'); check(backup instanceof HTMLButtonElement, '官方备份Switch不存在'); backup.click(); await pause();
  await fill('远端内容 · JSON 原值', 'false'); await click('保存远端');
  await until(() => target.textContent?.includes('实际来源：远端服务 · 远端已提交：是 · 本地备份已更新：否') === true, '关闭备份的远端提交状态未显示');
  check(settings.remoteValue() === false && settings.writes.at(-1)?.input['write_local_backup'] === false, '远端JSON原值或备份开关未传递');
  passed('远端保存保留false原值并显式关闭备份');
  check(button('保存此区').disabled && button('保存远端').disabled && button('读取远端').disabled, '无本地修订仍允许继续写入');
  check(target.textContent?.includes('请重新读取本地修订后继续写入'), '无修订未提示重查'); passed('远端提交无本地修订时要求重查');
  await click('读取配置'); await until(() => !button('保存远端').disabled, '重查修订后远端入口未恢复'); backup.click(); await pause();
  await fill('远端内容 · JSON 原值', '{"label":"远端与备份同步"}'); await click('保存远端');
  await until(() => target.textContent?.includes('实际来源：远端服务 · 远端已提交：是 · 本地备份已更新：是') === true, '远端与备份双成功状态未显示');
  check(settings.snapshot().revision === '6' && settings.writes.at(-1)?.input['write_local_backup'] === true, '开启备份未更新本地修订');
  passed('远端与本地备份成功独立呈现');
  await fill('配置区集合 · JSON', '{"general":{"label":"导入配置"},"extra":{"count":0}}'); await click('导入配置区');
  await until(() => settings.snapshot().revision === '7', '整批导入未完成');
  check(JSON.stringify(settings.snapshot().sections['extra']) === '{"count":0}', '导入丢失新增配置区'); passed('配置导入整批提交并保留零值');
  const beforeDelete = settings.writes.filter(entry => entry.operation === 'plugin.settings.delete').length;
  await click('删除此配置区'); await until(() => document.querySelector('[role="dialog"]') !== null, '删除配置区没有确认弹窗');
  await click('保留配置'); await until(() => !document.querySelector('[role="dialog"]'), '取消删除未关闭弹窗');
  check(settings.writes.filter(entry => entry.operation === 'plugin.settings.delete').length === beforeDelete, '取消删除仍提交了任务'); passed('配置删除取消零提交');
  await click('删除此配置区'); await click('确认删除'); await until(() => settings.snapshot().revision === '8', '确认删除未完成');
  check(!Object.hasOwn(settings.snapshot().sections, 'general'), '确认删除没有撤销目标配置区'); passed('确认删除使用当前修订');
  await select('配置归属', '工作区配置'); await until(() => button('保存此区').disabled, '配置归属切换仍消费旧修订');
  passed('切换配置归属撤销旧修订准入');
  await click('读取配置'); await until(() => !button('保存此区').disabled, '配置归属重查未完成');
  await fill('配置内容 · JSON', '{"draft":"主题切换必须保留"}');
  passed('保留配置草稿供主题与路由复验');
}
